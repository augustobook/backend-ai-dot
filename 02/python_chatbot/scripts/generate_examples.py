"""Generate `docs/EXAMPLES.md` with real questions and answers from the chatbot.

Run with:  uv run python scripts/generate_examples.py

Requires a valid OPENAI_API_KEY: every answer in the generated file is a real
output of the configured model.
"""

import logging
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from app.core.config import Settings, get_settings
from app.core.exceptions import ChatbotError, MissingAPIKeyError
from app.core.logging import configure_logging
from app.core.tracing import configure_tracing
from app.services.chat_service import ChatService, create_chat_service

logger = logging.getLogger(__name__)

OUTPUT_PATH = Path(__file__).resolve().parent.parent / "docs" / "EXAMPLES.md"


@dataclass(frozen=True, slots=True)
class Conversation:
    """A group of questions asked in the same session.

    Attributes:
        title: Section title in the generated document.
        note: What the conversation demonstrates.
        questions: Questions asked in order (follow-ups share the context).
    """

    title: str
    note: str
    questions: tuple[str, ...]


# Each conversation runs in its own session; questions inside a conversation share
# the history, which demonstrates the memory with a follow-up question.
CONVERSATIONS: tuple[Conversation, ...] = (
    Conversation(
        title="Lists and a follow-up question",
        note="The second question only makes sense with the context of the first (memory).",
        questions=(
            "Como criar uma lista em Python?",
            "E como adiciono e removo itens dessa lista?",
        ),
    ),
    Conversation(
        title="List vs. tuple",
        note="Conceptual comparison.",
        questions=("Qual a diferença entre lista e tupla?",),
    ),
    Conversation(
        title="List comprehensions",
        note="Concept with several code examples.",
        questions=("O que são list comprehensions? Dê exemplos.",),
    ),
    Conversation(
        title="Exception handling",
        note="Pitfalls and best practices.",
        questions=("Como tratar exceções em Python?",),
    ),
    Conversation(
        title="Decorators",
        note="Advanced topic explained step by step.",
        questions=("Explique o que são decorators.",),
    ),
    Conversation(
        title="Out-of-scope question",
        note="Not about Python: the tutor must decline politely.",
        questions=("Qual a capital da França?",),
    ),
)


def run_conversations(service: ChatService) -> list[tuple[Conversation, list[tuple[str, str]]]]:
    """Ask every question and collect the answers.

    Args:
        service: Chat service backed by the real model.

    Returns:
        Each conversation with its list of (question, answer) pairs.
    """
    results: list[tuple[Conversation, list[tuple[str, str]]]] = []
    for index, conversation in enumerate(CONVERSATIONS, start=1):
        session_id = f"examples-{index}"
        turns: list[tuple[str, str]] = []
        for question in conversation.questions:
            print(f"[{index}/{len(CONVERSATIONS)}] {question}")
            turns.append((question, service.ask(session_id, question, interface="script")))
        results.append((conversation, turns))
    return results


def render_markdown(
    results: list[tuple[Conversation, list[tuple[str, str]]]], settings: Settings
) -> str:
    """Render the collected answers as Markdown.

    Args:
        results: Output of `run_conversations`.
        settings: Settings used (the model name is recorded in the document).

    Returns:
        The content of `docs/EXAMPLES.md`.
    """
    generated_at = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Example questions and answers",
        "",
        "Real answers generated by `uv run python scripts/generate_examples.py`.",
        "",
        f"- Model: `{settings.openai_model}` (temperature {settings.openai_temperature})",
        f"- Generated at: {generated_at}",
        "",
    ]
    for index, (conversation, turns) in enumerate(results, start=1):
        lines += [f"## {index}. {conversation.title}", "", f"> {conversation.note}", ""]
        for question, answer in turns:
            lines += [f"### 🧑 {question}", "", answer.strip(), "", "---", ""]
    return "\n".join(lines)


def main() -> int:
    """Generate the examples file.

    Returns:
        The process exit code.
    """
    settings = get_settings()
    configure_logging(settings.log_level)
    configure_tracing(settings)

    try:
        service = create_chat_service(settings)
        results = run_conversations(service)
    except MissingAPIKeyError as exc:
        print(f"Configuration error: {exc.user_message}")
        return 1
    except ChatbotError as exc:
        print(f"Could not generate the examples: {exc.user_message}")
        return 1

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(render_markdown(results, settings), encoding="utf-8")
    print(f"Examples written to {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
